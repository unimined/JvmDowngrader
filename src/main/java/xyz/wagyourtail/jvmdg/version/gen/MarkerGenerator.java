package xyz.wagyourtail.jvmdg.version.gen;

import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.ClassNode;
import xyz.wagyourtail.jvmdg.version.Adapter;
import xyz.wagyourtail.jvmdg.version.VersionProvider;
import xyz.wagyourtail.jvmdg.version.map.ClassStubEntry;

import java.io.IOException;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;

/**
 * Emits {@code <stub>$Marker} interfaces for every SUPERTYPE-mode adapter
 * that doesn't hand-declare one — the transform injects these into
 * downgraded classes whose {@code implements} clause named the retro type,
 * and the {@code META-INF/jvmdg/retrotypes} rows list the name, so the
 * interface must physically exist at runtime. Emitted at {@code V1_8}
 * (the lowest runtime floor) — they ship inside the api jar and load on
 * every supported target.
 */
public final class MarkerGenerator implements ApiGenerator {

    @Override
    public String name() {
        return "markers";
    }

    @Override
    public void generate(GenContext ctx) throws IOException {
        Set<String> emitted = new HashSet<>();
        for (VersionProvider vp : ctx.providers) {
            for (Map.Entry<org.objectweb.asm.Type, ClassStubEntry> e : vp.classStubs.entrySet()) {
                ClassStubEntry stub = e.getValue();
                if (stub.mode != Adapter.Mode.SUPERTYPE || !emitted.add(stub.stubType.getInternalName())) {
                    continue;
                }
                String marker = stub.stubType.getInternalName() + "$Marker";
                if (ctx.declared(marker)) {
                    continue; // adapter declares its own Marker nested interface
                }
                ClassNode node = new ClassNode();
                node.visit(Opcodes.V1_8,
                    Opcodes.ACC_PUBLIC | Opcodes.ACC_ABSTRACT | Opcodes.ACC_INTERFACE,
                    marker, null, "java/lang/Object", null);
                node.visitEnd();
                ctx.emit(marker, node, dump(marker, stub.stubType.getInternalName()));
            }
        }
    }

    private static String dump(String marker, String adapter) {
        int last = marker.lastIndexOf('/');
        String pkg = last < 0 ? "" : marker.substring(0, last).replace('/', '.');
        StringBuilder sb = new StringBuilder();
        sb.append("// generated by StubIndexWriter — inspection dump; the .class is authoritative\n");
        if (!pkg.isEmpty()) {
            sb.append("package ").append(pkg).append(";\n\n");
        }
        sb.append("public interface ").append(marker.substring(last + 1).replace('$', '.'));
        sb.append(" /* nested in ").append(adapter.replace('/', '.')).append(" */ {\n}\n");
        return sb.toString();
    }

}
